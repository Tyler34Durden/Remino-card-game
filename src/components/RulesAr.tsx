import type { RoomSettings } from "../../shared/types.ts";

/** Card sequences such as A-2-3 must keep their left-to-right order inside Arabic text. */
function Seq({ children }: { children: string }) {
  return (
    <bdi dir="ltr" className="seq">
      {children}
    </bdi>
  );
}

/** The Arabic rules text. It follows the room settings in the same way as the English text. */
export function RulesAr({ s }: { s: RoomSettings }) {
  return (
    <>
      <h3>الهدف</h3>
      <p>تخلّص من كل أوراق يدك. النقاط نقاط جزاء، فالفائز هو صاحب أقل مجموع. أول لاعب يرمي ورقته الأخيرة يفوز بالجولة ويسجل 0.</p>

      <h3>الورق والتوزيع</h3>
      <ul>
        <li>
          تُلعب اللعبة بمجموعتي ورق كاملتين
          {s.jokerCount > 0 ? `، مع جوكر عدده ${s.jokerCount}، فيكون المجموع ${104 + s.jokerCount} ورقة` : " بدون جوكر، فيكون المجموع 104 ورقات"}. الورقتان المتطابقتان من
          المجموعتين تُعدّان ورقتين مختلفتين.
        </li>
        <li>يأخذ كل لاعب 14 ورقة. الباقي يشكّل كومة السحب المقلوبة، وتُكشف ورقة واحدة لتبدأ كومة الرمي.</li>
        <li>ينتقل التوزيع مقعداً واحداً في كل جولة، ويدور اللعب بالترتيب بدءاً من اللاعب الذي يلي الموزّع.</li>
      </ul>

      <h3>دورك</h3>
      <ol>
        <li>
          خذ ورقة واحدة: إما الورقة العليا من <strong>كومة السحب</strong>، وإما الورقة العليا من <strong>كومة الرمي</strong>. لا يمكن الجمع بينهما أبداً.
        </li>
        <li>نزّل ما يسمح به اختيارك.</li>
        <li>ارمِ ورقة واحدة، وبذلك ينتهي دورك. لا يُرمى الجوكر إلا إذا كان ورقتك الأخيرة.</li>
        <li>لا يجوز رمي ورقة تصلح للإضافة إلى تنزيلة على الطاولة. إذا كانت كل أوراقك تصلح للطاولة جاز رمي أي واحدة منها.</li>
      </ol>
      <ul>
        <li>
          <strong>بعد السحب من كومة السحب</strong> لا يمكنك الفتح. أما إذا كنت قد فتحت من قبل فيمكنك تنزيل تنزيلات جديدة، والإضافة إلى تنزيلات الطاولة، وتبديل
          الجوكر، كما في أي دور آخر.
        </li>
        <li>
          <strong>إذا أخذت الورقة المرمية</strong> فيجب أن تضعها هي نفسها في تنزيلة جديدة مع أوراق من يدك في الدور ذاته. إضافتها إلى تنزيلة موجودة على الطاولة لا
          تكفي. لا يمكنك الاحتفاظ بها ولا رميها من جديد. في هذه اللعبة تجهّز لعبك أولاً ثم تؤكده، فلا تُحسب عليك أخذة غير صحيحة.
        </li>
        <li>عندما تنفد كومة السحب تُخلط كومة الرمي لتصبح كومة سحب جديدة، وتبقى ورقتها العليا في مكانها.</li>
      </ul>

      <h3>التنزيلات</h3>
      <ul>
        <li>
          <strong>المجموعة</strong> ثلاث أوراق أو أربع من الرقم نفسه، كل واحدة من نوع مختلف. لا تجتمع ورقتان متطابقتان في مجموعة واحدة.
        </li>
        <li>
          <strong>التسلسل</strong> ثلاث أوراق متتالية أو أكثر من نوع واحد. يمكن أن يكون الآس في الأول (<Seq>A-2-3</Seq>) أو في الآخر (<Seq>Q-K-A</Seq>). لا يمكن أن
          يلتف التسلسل (<Seq>K-A-2</Seq>).
        </li>
        <li>بعد أن تفتح يمكنك الإضافة إلى أي تنزيلة على الطاولة مهما كان صاحبها.</li>
      </ul>

      <h3>الفتح</h3>
      {s.openingRequired ? (
        <ul>
          <li>
            يجب أن يبلغ مجموع أول لعب لك <strong>{s.openingThreshold} نقطة</strong> على الأقل في دور واحد، وأن يبدأ ذلك الدور بأخذ الورقة المرمية واستعمالها في
            تنزيلة جديدة.
          </li>
          <li>
            أوراق الأرقام تُحسب بقيمتها. الولد والبنت والشايب بـ 10. الآس بـ 1 في <Seq>A-2-3</Seq> وبـ 10 في <Seq>Q-K-A</Seq> أو في مجموعة.
          </li>
          <li>التنزيلات الجديدة وحدها تُحسب. الورقة التي تضيفها إلى تنزيلة موجودة على الطاولة، أو التي تحل محل جوكر، لا تضيف شيئاً إلى مجموع الفتح.</li>
          <li>يمكن الجمع بين عدة تنزيلات وإضافات. نقاط الفتح تفتح لك اللعب فقط، ولا تُضاف إلى مجموعك أبداً.</li>
        </ul>
      ) : (
        <p>لا يوجد حد للفتح في هذه الغرفة. لكن أول لعب لك يجب أن يبدأ بأخذ الورقة المرمية واستعمالها في تنزيلة جديدة، وبعدها تُعدّ فاتحاً.</p>
      )}

      {s.jokerCount > 0 && (
        <>
          <h3>الجوكر</h3>
          <ul>
            <li>يحل الجوكر محل ورقة ناقصة في مجموعة أو تسلسل. في التسلسل يمثل ورقة واحدة بعينها.</li>
            <li>
              في المجموعة يمثل الجوكر أي نوع ناقص. فمع <Seq>A♠</Seq> و<Seq>A♥</Seq> وجوكر، يمكن أن تحل محله <Seq>A♦</Seq> أو <Seq>A♣</Seq>.
            </li>
            <li>التنزيلة الجديدة تحتاج إلى ورقتين عاديتين على الأقل.</li>
            <li>إذا كانت في يدك ورقة يمثلها جوكر على الطاولة فيمكنك وضعها مكانه وأخذ الجوكر إلى يدك. لست ملزماً باستعمال الجوكر فوراً.</li>
            <li>يمكن وضع الجوكر في تنزيلة جديدة في أي وقت. أما إضافته إلى تنزيلة موجودة على الطاولة فلا تجوز إلا في الدور الذي تنهي فيه أوراقك، بحيث تبقى ورقة واحدة فقط لترميها.</li>
            <li>لا يُرمى الجوكر إلا إذا كان ورقتك الأخيرة. الجوكر الباقي في يدك يكلّفك 25 نقطة.</li>
            <li>إذا كان في يدك ورقتان أو أكثر وكلها جوكر فإن دورك يمر بدون رمي.</li>
          </ul>
        </>
      )}

      <h3>إنهاء الجولة</h3>
      <p>تفوز بالجولة عندما ترمي ورقتك الأخيرة. لا يمكنك الإنهاء بتنزيل كل أوراقك، فكل لعب يجب أن يترك في يدك ورقة واحدة لترميها.</p>

      <h3>الحساب</h3>
      <ul>
        <li>الفائز بالجولة يسجل 0، والأوراق المنزّلة على الطاولة لا تُحسب.</li>
        <li>
          يضيف كل لاعب آخر قيمة الأوراق الباقية في يده: أوراق الأرقام بقيمتها، والولد والبنت والشايب والآس بـ 10{s.jokerCount > 0 ? "، والجوكر بـ 25" : ""}.
        </li>
        {s.matchFormat === "score-limit" ? (
          <li>
            تنتهي المباراة بعد الجولة التي يبلغ فيها أي لاعب <strong>{s.scoreLimit}</strong> نقطة جزاء. الفائز صاحب أقل مجموع.
          </li>
        ) : (
          <li>
            تستمر المباراة <strong>{s.roundCount}</strong> جولات. الفائز صاحب أقل مجموع.
          </li>
        )}
        <li>لا تنتهي المباراة بالتعادل. إذا تساوى أكثر من لاعب في أقل مجموع تُلعب جولات إضافية حتى ينفرد لاعب واحد بالصدارة.</li>
      </ul>

      <h3>الغرف</h3>
      <ul>
        <li>المقاعد الفارغة تملؤها روبوتات تلعب بالقواعد نفسها تماماً.</li>
        <li>من ينضم أثناء المباراة ينتظر الجولة التالية، ويأخذ مكان روبوت، ويبدأ بأعلى مجموع موجود.</li>
        <li>إذا انقطع اتصالك يلعب روبوت مكانك بعد انتظار قصير. افتح الصفحة من جديد لتستعيد مقعدك.</li>
        <li>إذا غادر المضيف تُغلق الغرفة.</li>
      </ul>
    </>
  );
}
